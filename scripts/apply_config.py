def apply_caveman(target: Path, caveman_intent: dict[str, Any] | None, *, dry_run: bool = False) -> SectionResult:
    sr = SectionResult(name="features.caveman", ok=True)
    if not caveman_intent:
        sr.detail = "no caveman intent in bundle — no-op"
        return sr

    enabled = bool(caveman_intent.get("enabled"))
    mode = caveman_intent.get("mode", "ultra")
    components_dict = caveman_intent.get("components") or {}
    requested = [k for k, v in components_dict.items() if v]

    if dry_run:
        if enabled:
            sr.changes.append(
                f"DRY-RUN would invoke: python -m scripts.caveman on --mode {mode} "
                f"--components {','.join(requested) or 'response_style'}"
            )
        else:
            sr.changes.append("DRY-RUN would invoke: python -m scripts.caveman off")
        return sr

    if enabled:
        cmd = [sys.executable, "-m", "scripts.caveman", "on", "--mode", mode]
        if requested:
            cmd.extend(["--components", ",".join(requested)])
    else:
        cmd = [sys.executable, "-m", "scripts.caveman", "off"]

    try:
        proc = subprocess.run(
            cmd,
            cwd=str(target),
            capture_output=True,
            text=True,
            check=False,
            encoding="utf-8",
            errors="replace",
        )
    except OSError as e:
        sr.ok = False
        sr.detail = f"subprocess launch failed: {e}"
        return sr

    if proc.returncode != 0:
        sr.ok = False
        sr.detail = (
            f"caveman CLI exit {proc.returncode}\n"
            f"  stdout: {proc.stdout.strip()[:500]}\n"
            f"  stderr: {proc.stderr.strip()[:500]}"
        )
        return sr
    sr.changes.append(f"invoked: {' '.join(cmd)}")
    if proc.stdout.strip():
        sr.changes.append(f"caveman output: {proc.stdout.strip()[:300]}")
    return sr


