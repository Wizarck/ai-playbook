def apply_rules(
    target: Path, bundle: dict[str, Any], rules_inventory: dict[str, Any] | None
) -> tuple[SectionResult, dict[str, str]]:
    """Write rules-toggle.json + return env var entries derived from advanced{}.

    Returns (SectionResult, env_entries) where env_entries is a dict of
    {ENV_VAR: VALUE} to be merged into feature-flags.env by the global-flags
    section. Empty dict if no advanced sub-toggles diverged from defaults.
    """
    sr = SectionResult(name="rules", ok=True)
    rules = bundle.get("rules") or {}
    env_entries: dict[str, str] = {}

    if not rules:
        sr.detail = "no rules in bundle — no-op"
        return sr, env_entries

    # Build the state file dict.
    state = rules_toggle.default_state()
    state["rules"] = {}
    state["applied_at"] = datetime.now(UTC).isoformat()
    state["applied_by"] = _actor()

    # Orphan prune (D-plan Fase B): a bundle slug absent from the live inventory
    # is a rule that no longer exists on disk — drop it so deleting a rule never
    # leaves dangling consumer toggle state. Guard: only prune when we actually
    # have an inventory; `None` (transient build error / detached consumer) keeps
    # every slug so a missing inventory never silently wipes valid toggles.
    known: set[str] | None = None
    if rules_inventory is not None:
        known = {r.get("slug") for r in rules_inventory.get("rules", [])}

    for slug, entry in rules.items():
        if not isinstance(entry, dict):
            sr.ok = False
            sr.detail = f"rule {slug!r} is not a dict"
            return sr, env_entries
        if known is not None and slug not in known:
            sr.changes.append(f"pruned unknown rule: {slug}")
            continue
        state["rules"][slug] = dict(entry)
        sr.changes.append(f"{slug}: {('OFF' if entry.get('enabled') is False else 'partial')}")

    try:
        rules_toggle.write_state(target, state)
    except Exception as e:  # noqa: BLE001 — surface to report
        sr.ok = False
        sr.detail = f"failed to write rules-toggle.json: {e}"
        return sr, env_entries
    sr.changes.append(f"wrote {rules_toggle.state_path(target)}")

    # Derive env entries from advanced{} via inventory mapping.
    if rules_inventory is not None:
        inv_by_slug = {r["slug"]: r for r in rules_inventory.get("rules", [])}
        for slug, entry in rules.items():
            advanced = entry.get("advanced") or {}
            inv_rule = inv_by_slug.get(slug)
            if not inv_rule:
                continue
            for adv in inv_rule.get("advanced", []) or []:
                key = adv.get("key")
                if key is None or key not in advanced:
                    continue
                value = advanced[key]
                env_var = adv.get("env_var")
                if not env_var:
                    continue
                v_on = adv.get("value_on", "1")
                v_off = adv.get("value_off", "0")
                env_entries[env_var] = v_on if value else v_off

    return sr, env_entries


