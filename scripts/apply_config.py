# Ordered identity of the sections apply() emits. Child consequences
# (materialise / render) follow their parent enforce section. This replaces the
# hand-typed "Section N" comments (which had a duplicate "Section 5").
SECTION_ORDER = (
    "rules",
    "features.caveman",
    "features.graphify",
    "features.ponytail",
    "global_flags",
    "global_flags.telemetry_weekly_issue",
    "skills_enforce",
    "skills_enforce.materialise",
    "mcps_enforce",
    "mcps_enforce.render",
    "managed_files",
    "applied-bundle",
    "files-state-sidecar",
    "dashboard-sidecar",
)


_MCP_BUNDLE_SECTIONS: tuple[str, ...] = ("mcps_enforce", "mcp_project_servers")


def _has_mcp_intent(bundle: dict[str, Any]) -> bool:
    """True when the bundle carries an MCP-related section.

    ``apply_mcp_render`` re-renders ``.mcp.json`` + ``.gemini/settings.json`` (and
    a global gemini config) from the MCP SSOT. That render is the *consequence* of
    an MCP intent — running it for a bundle that says nothing about MCP (e.g. a
    caveman-only toggle) rewrites the consumer's entire MCP surface for an
    unrelated change. Gate it on a declared MCP section.
    """
    return any(section in bundle for section in _MCP_BUNDLE_SECTIONS)


def _skipped_mcp_render_section(*, dry_run: bool = False) -> SectionResult:
    """The ``mcps_enforce.render`` slot, reported as a no-op when MCP intent absent."""
    prefix = "DRY-RUN: " if dry_run else ""
    return SectionResult(
        name="mcps_enforce.render",
        section_id="mcps_enforce.render",
        ok=True,
        detail=(
            f"{prefix}skipped — no MCP intent in bundle "
            "(mcps_enforce / mcp_project_servers absent)"
        ),
    )


_TELEMETRY_WORKFLOW_REL = ".github/workflows/rule-event-report-weekly.yml"
_TELEMETRY_WORKFLOW_TMPL = (
    "templates/new-project/.github/workflows/rule-event-report-weekly.yml.tmpl"
)


def apply_telemetry_weekly_issue(
    target: Path, bundle: dict[str, Any], *, dry_run: bool = False
) -> SectionResult:
    """Consequence of the ``telemetry_weekly_issue`` global flag.

    When ON, **seed** the weekly telemetry-report workflow into the consumer's
    ``.github/workflows/`` (the ``telemetry-report`` label is created at install
    by ``bootstrap``). Seed-only: an existing file is never clobbered — the
    consumer owns it once seeded (delete it to re-seed an updated version, or to
    turn the feature off). When the flag is OFF/absent this is a no-op; removal of
    an already-seeded file is a documented manual step (a scheduled workflow can't
    read the gitignored bundle, so the file's presence IS the toggle).

    Best-effort: a missing playbook root or a write failure is reported but never
    flips the overall apply verdict.
    """
    sr = SectionResult(
        name="global_flags.telemetry_weekly_issue",
        section_id="global_flags.telemetry_weekly_issue",
        ok=True,
    )
    enabled = bool((bundle.get("global_flags") or {}).get("telemetry_weekly_issue"))
    prefix = "DRY-RUN: " if dry_run else ""
    if not enabled:
        sr.detail = f"{prefix}skipped — telemetry_weekly_issue flag off/absent"
        return sr

    dest = target / _TELEMETRY_WORKFLOW_REL
    if dest.is_file():
        sr.detail = f"{prefix}seed-only: {_TELEMETRY_WORKFLOW_REL} already present — kept as-is"
        return sr

    if dry_run:
        sr.detail = f"DRY-RUN: would seed {_TELEMETRY_WORKFLOW_REL}"
        return sr

    try:
        root = rules_toggle.find_playbook_root()
        if root is None:
            sr.detail = "skipped: playbook root not found — cannot seed workflow"
            return sr
        tmpl = root / _TELEMETRY_WORKFLOW_TMPL
        content = tmpl.read_text(encoding="utf-8")
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(content, encoding="utf-8")
        sr.detail = f"seeded {_TELEMETRY_WORKFLOW_REL} (telemetry-report label created at install)"
        sr.changes.append(f"+ {_TELEMETRY_WORKFLOW_REL}")
    except Exception as exc:  # noqa: BLE001 — never abort apply on a seed failure
        sr.detail = f"skipped: seed raised {type(exc).__name__}: {exc}"
    return sr


def apply_skills_materialise(target: Path, *, dry_run: bool = False) -> SectionResult:
    """Consequence of ``skills_enforce``: mirror the enforcement-filtered skills.

    Best-effort: a source-missing consumer (submodule not yet initialised) or a
    write failure is reported in the section detail but does NOT flip the overall
    apply verdict — matching the established bootstrap discipline of warning and
    continuing on skills errors.
    """
    sr = SectionResult(
        name="skills_enforce.materialise",
        section_id="skills_enforce.materialise",
        ok=True,
    )
    try:
        from scripts.materialise_skills import materialise_skills

        res = materialise_skills(target, dry_run=dry_run, quiet=True)
        sr.detail = res.summary or ("dry-run" if dry_run else "materialised")
        if res.user_dirs_preserved:
            sr.changes.append(
                f"preserved {len(res.user_dirs_preserved)} user-added skill dir(s)"
            )
        if res.stale_removed:
            sr.changes.append(
                f"removed {len(res.stale_removed)} stale playbook skill dir(s)"
            )
        if res.errors:
            sr.changes.append("⚠ " + "; ".join(res.errors)[:300])
    except Exception as exc:  # noqa: BLE001 — never abort apply on materialise
        sr.detail = f"skipped: materialise raised {type(exc).__name__}: {exc}"
    return sr


def apply_mcp_render(target: Path, *, dry_run: bool = False) -> SectionResult:
    """Consequence of ``mcps_enforce``: render .mcp.json + .gemini/settings.json.

    Best-effort: a render failure (e.g. playbook root not resolvable) is reported
    but does not flip the overall apply verdict.
    """
    sr = SectionResult(
        name="mcps_enforce.render",
        section_id="mcps_enforce.render",
        ok=True,
    )
    argv = ["--consumer-root", str(target)]
    if dry_run:
        argv.append("--dry-run")
    try:
        from scripts.mcp import render as _mcp_render

        rc = _mcp_render.main(argv)
        if rc == 0:
            sr.detail = (
                "would render .mcp.json + .gemini/settings.json"
                if dry_run else "rendered .mcp.json + .gemini/settings.json"
            )
        else:
            sr.detail = f"mcp render exited rc={rc}"
            sr.changes.append("⚠ MCP configs may be stale")
    except SystemExit as exc:  # render may sys.exit on a fatal gate
        sr.detail = f"skipped: mcp render exited ({getattr(exc, 'code', '?')})"
    except Exception as exc:  # noqa: BLE001 — never abort apply on render
        sr.detail = f"skipped: mcp render raised {type(exc).__name__}: {exc}"
    return sr


def _write_applied_bundle(target: Path, bundle: dict[str, Any]) -> SectionResult:
    """Persist the just-applied bundle as the consumer's 'last applied' state.

    Writes two sibling files under ``<target>/.ai-playbook/``:

    - ``applied-config.json`` — canonical source of truth. ``apply_config`` reads
      it on the next run; it is also the file the user re-edits or commits to
      version control externally if they want a diff trail.
    - ``applied-config.js`` — ``window.APPLIED_CONFIG = {...};`` sidecar. The
      HTML config UI loads this via ``<script src>`` so it can render the
      currently-applied state when opened over ``file://`` (where ``fetch()``
      is blocked by most browsers). The data is identical to the JSON.

    Both files are gitignored. The JS sidecar is regenerated on every apply,
    so a manual edit to the JSON without re-running ``apply_config`` will leave
    the UI showing stale state until the next apply.
    """
    sr = SectionResult(name="applied-bundle", ok=True)
    try:
        state_dir = target / STATE_DIR_NAME
        state_dir.mkdir(parents=True, exist_ok=True)
        json_path = state_dir / APPLIED_BUNDLE_FILENAME
        js_path = state_dir / APPLIED_BUNDLE_JS_FILENAME
        body = json.dumps(bundle, indent=2, ensure_ascii=False, sort_keys=False)
        json_path.write_text(body + "\n", encoding="utf-8")
        js_body = (
            "/* Auto-generated by scripts/apply_config.py. DO NOT EDIT MANUALLY. */\n"
            "/* Source of truth: applied-config.json (sibling). */\n"
            f"window.APPLIED_CONFIG = {body};\n"
        )
        js_path.write_text(js_body, encoding="utf-8")
        sr.changes.append(f"wrote {json_path}")
        sr.changes.append(f"wrote {js_path}")
    except OSError as e:
        sr.ok = False
        sr.detail = f"failed to persist applied bundle: {e}"
    return sr


def apply(bundle_path: Path, *, target: Path | None = None, dry_run: bool = False) -> ApplyReport:
    bundle_path = bundle_path.expanduser().resolve()
    if not bundle_path.is_file():
        raise FileNotFoundError(f"bundle not found: {bundle_path}")
    raw = bundle_path.read_text(encoding="utf-8")
    try:
        bundle = json.loads(raw)
    except json.JSONDecodeError as e:
        raise ValueError(f"bundle is not valid JSON: {e}") from e

    schema = _load_bundle_schema()
    try:
        jsonschema.validate(bundle, schema)
    except jsonschema.ValidationError as e:
        raise ValueError(f"bundle fails schema validation: {e.message}") from e

    if target is None:
        target = rules_toggle.find_project_root()
        if target is None:
            raise FileNotFoundError(
                "target project root not found (no AGENTS.md on parent chain). "
                "Pass --target PATH."
            )
    target = target.expanduser().resolve()

    report = ApplyReport(target=target, bundle_path=bundle_path)

    # Pre-flight: caveman's enabled-state before any mutation, so a rolled-back
    # managed-files transaction can surface a precise manual reconcile step
    # (caveman is a subprocess and is not covered by the session rollback).
    caveman_preflight = _caveman_preflight(target)
    graphify_preflight = _graphify_preflight(target)
    ponytail_preflight = _ponytail_preflight(target)

    rules_inv = _load_rules_inventory_live()
    global_flags_inv = _load_inventory("global-flags-inventory.json")

    if dry_run:
        # Section results in dry-run mode are descriptive only.
        sr = SectionResult(name="rules", ok=True)
        sr.detail = f"DRY-RUN would write {len(bundle.get('rules') or {})} rule entries"
        report.sections.append(sr)
        report.sections.append(apply_caveman(target, (bundle.get("features") or {}).get("caveman"), dry_run=True))
        report.sections.append(apply_graphify(target, (bundle.get("features") or {}).get("graphify"), dry_run=True))
        report.sections.append(apply_ponytail(target, (bundle.get("features") or {}).get("ponytail"), dry_run=True))
        sr2 = SectionResult(name="global_flags", ok=True)
        sr2.detail = f"DRY-RUN would write {len(bundle.get('global_flags') or {})} global flag entries"
        report.sections.append(sr2)
        report.sections.append(apply_telemetry_weekly_issue(target, bundle, dry_run=True))
        report.sections.append(apply_skills_enforce(target, bundle, dry_run=True))
        report.sections.append(apply_skills_materialise(target, dry_run=True))
        report.sections.append(apply_mcps_enforce(target, bundle, dry_run=True))
        if _has_mcp_intent(bundle):
            report.sections.append(apply_mcp_render(target, dry_run=True))
        else:
            report.sections.append(_skipped_mcp_render_section(dry_run=True))
        # Dry-run managed files: count what would be touched.
        try:
            playbook_root_for_mf = rules_toggle.find_playbook_root()
            mf_dry = _managed_files.apply_managed_files(
                consumer_root=target,
                playbook_root=playbook_root_for_mf or Path("."),
                bundle=bundle,
                dry_run=True,
            )
            mf_sr_dry = SectionResult(
                name="managed_files", ok=mf_dry.ok, detail=mf_dry.detail,
            )
            mf_sr_dry.changes.extend(mf_dry.changes)
            report.sections.append(mf_sr_dry)
        except Exception as exc:  # noqa: BLE001
            report.sections.append(SectionResult(
                name="managed_files", ok=False,
                detail=f"dry-run failed: {exc}",
            ))
        sr3 = SectionResult(name="applied-bundle", ok=True)
        sr3.detail = "DRY-RUN would persist applied-config.json + applied-config.js"
        report.sections.append(sr3)
        return report

    # Section 1: rules (also produces env entries for advanced sub-toggles)
    rules_sr, rules_env_entries = apply_rules(target, bundle, rules_inv)
    report.sections.append(rules_sr)
    _audit_append(target, {
        "ts": datetime.now(UTC).isoformat(),
        "actor": _actor(),
        "action": "apply-config:rules",
        "ok": rules_sr.ok,
        "detail": rules_sr.detail,
        "bundle": bundle_path.as_posix(),
    })

    # Section 2: features.caveman. Runs before MCP render (section 5b) so the
    # mcp_shrink post-hook sees the rendered .mcp.json (locked ordering). caveman
    # is a non-transactional subprocess — track whether it actually mutated so a
    # later rollback can surface the manual reconcile step.
    cv_sr = apply_caveman(target, (bundle.get("features") or {}).get("caveman"))
    caveman_mutated = any(c.startswith("invoked:") for c in cv_sr.changes)
    report.sections.append(cv_sr)
    _audit_append(target, {
        "ts": datetime.now(UTC).isoformat(),
        "actor": _actor(),
        "action": "apply-config:caveman",
        "ok": cv_sr.ok,
        "detail": cv_sr.detail,
        "bundle": bundle_path.as_posix(),
    })

    # Section 2b: features.graphify. Like caveman, a non-transactional subprocess
    # that mutates AGENTS.md (+ .gitignore) — track whether it actually mutated so
    # a later managed-files rollback can surface the manual reconcile step.
    gx_sr = apply_graphify(target, (bundle.get("features") or {}).get("graphify"))
    graphify_mutated = any(c.startswith("invoked:") for c in gx_sr.changes)
    report.sections.append(gx_sr)
    _audit_append(target, {
        "ts": datetime.now(UTC).isoformat(),
        "actor": _actor(),
        "action": "apply-config:graphify",
        "ok": gx_sr.ok,
        "detail": gx_sr.detail,
        "bundle": bundle_path.as_posix(),
    })

    # Section 2c: features.ponytail. Like caveman/graphify, a non-transactional
    # subprocess that mutates AGENTS.md — track whether it actually mutated so a
    # later managed-files rollback can surface the manual reconcile step.
    px_sr = apply_ponytail(target, (bundle.get("features") or {}).get("ponytail"))
    ponytail_mutated = any(c.startswith("invoked:") for c in px_sr.changes)
    report.sections.append(px_sr)
    _audit_append(target, {
        "ts": datetime.now(UTC).isoformat(),
        "actor": _actor(),
        "action": "apply-config:ponytail",
        "ok": px_sr.ok,
        "detail": px_sr.detail,
        "bundle": bundle_path.as_posix(),
    })

    # Section 3: global_flags (merges rules-derived env entries)
    gf_sr = apply_global_flags(target, bundle, rules_env_entries, global_flags_inv)
    report.sections.append(gf_sr)
    _audit_append(target, {
        "ts": datetime.now(UTC).isoformat(),
        "actor": _actor(),
        "action": "apply-config:global_flags",
        "ok": gf_sr.ok,
        "detail": gf_sr.detail,
        "bundle": bundle_path.as_posix(),
    })

    # Section 3b: telemetry_weekly_issue — consequence of the global flag. Seeds
    # the weekly telemetry-report workflow when ON (label created at install).
    tw_sr = apply_telemetry_weekly_issue(target, bundle)
    report.sections.append(tw_sr)
    _audit_append(target, {
        "ts": datetime.now(UTC).isoformat(),
        "actor": _actor(),
        "action": "apply-config:telemetry_weekly_issue",
        "ok": tw_sr.ok,
        "detail": tw_sr.detail,
        "bundle": bundle_path.as_posix(),
    })

    # Section 4: skills_enforce → .ai-playbook-state/skills-enforce.json
    se_sr = apply_skills_enforce(target, bundle)
    report.sections.append(se_sr)
    _audit_append(target, {
        "ts": datetime.now(UTC).isoformat(),
        "actor": _actor(),
        "action": "apply-config:skills_enforce",
        "ok": se_sr.ok,
        "detail": se_sr.detail,
        "bundle": bundle_path.as_posix(),
    })

    # Section 4b: skills materialisation — the consequence of skills_enforce.
    # The enforce state file (written above) is the INPUT to the mirror.
    sm_sr = apply_skills_materialise(target)
    report.sections.append(sm_sr)
    _audit_append(target, {
        "ts": datetime.now(UTC).isoformat(),
        "actor": _actor(),
        "action": "apply-config:skills_materialise",
        "ok": sm_sr.ok,
        "detail": sm_sr.detail,
        "bundle": bundle_path.as_posix(),
    })

    # Section 5: mcps_enforce → .ai-playbook-state/mcps-enforce.json
    me_sr = apply_mcps_enforce(target, bundle)
    report.sections.append(me_sr)
    _audit_append(target, {
        "ts": datetime.now(UTC).isoformat(),
        "actor": _actor(),
        "action": "apply-config:mcps_enforce",
        "ok": me_sr.ok,
        "detail": me_sr.detail,
        "bundle": bundle_path.as_posix(),
    })

    # Section 5b: MCP render — the consequence of mcps_enforce. Reads the
    # disabled-MCP state file (written above) and renders the per-model configs.
    # Gated on a declared MCP intent so an unrelated bundle (e.g. a caveman-only
    # toggle) never rewrites the consumer's MCP surface + the global gemini config.
    mr_sr = (
        apply_mcp_render(target) if _has_mcp_intent(bundle)
        else _skipped_mcp_render_section()
    )
    report.sections.append(mr_sr)
    _audit_append(target, {
        "ts": datetime.now(UTC).isoformat(),
        "actor": _actor(),
        "action": "apply-config:mcp_render",
        "ok": mr_sr.ok,
        "detail": mr_sr.detail,
        "bundle": bundle_path.as_posix(),
    })

    # Section 6: managed files (AGENTS.md / .gitignore / .pre-commit / etc.).
    # Only renders files whose trigger section is present in the bundle so
    # legacy bundles stay no-op for this section. Updates bundle.file_states
    # in-memory; the applied-bundle persistence below picks up the new manifest.
    mf_sr_section = SectionResult(name="managed_files", ok=True)
    try:
        playbook_root_for_mf = rules_toggle.find_playbook_root()
        if playbook_root_for_mf is None:
            mf_sr_section.detail = "playbook root not found — managed_files skipped"
        else:
            session_id = f"apply-{datetime.now(UTC).strftime('%Y-%m-%dT%H-%M-%SZ')}"
            mf_result = _managed_files.apply_managed_files(
                consumer_root=target,
                playbook_root=playbook_root_for_mf,
                bundle=bundle,
                session_id=session_id,
            )
            mf_sr_section.ok = mf_result.ok
            mf_sr_section.detail = mf_result.detail
            mf_sr_section.changes.extend(mf_result.changes)
            # caveman ran (and possibly mutated AGENTS.md) before this batch; if
            # the batch rolled back, caveman's non-transactional changes are now
            # ahead of the reverted files — surface the manual reconcile step.
            if caveman_mutated and any("rolled back" in c for c in mf_result.changes):
                pre_enabled = bool((caveman_preflight or {}).get("enabled"))
                mf_sr_section.changes.append(
                    "⚠ caveman mutated AGENTS.md/state earlier this reconcile but the "
                    "managed-files batch rolled back; caveman is not transactional. "
                    f"Restore its pre-apply state with `python -m scripts.caveman "
                    f"{'on' if pre_enabled else 'off'}`, then re-run reconcile "
                    "(or `python -m scripts.caveman rollback --yes`)."
                )
            if graphify_mutated and any("rolled back" in c for c in mf_result.changes):
                gx_pre_enabled = bool((graphify_preflight or {}).get("enabled"))
                mf_sr_section.changes.append(
                    "⚠ graphify mutated AGENTS.md/.gitignore earlier this reconcile but the "
                    "managed-files batch rolled back; graphify is not transactional. "
                    f"Restore its pre-apply state with `python -m scripts.graphify "
                    f"{'on' if gx_pre_enabled else 'off'}`, then re-run reconcile."
                )
            if ponytail_mutated and any("rolled back" in c for c in mf_result.changes):
                px_pre_enabled = bool((ponytail_preflight or {}).get("enabled"))
                mf_sr_section.changes.append(
                    "⚠ ponytail mutated AGENTS.md earlier this reconcile but the "
                    "managed-files batch rolled back; ponytail is not transactional. "
                    f"Restore its pre-apply state with `python -m scripts.ponytail "
                    f"{'on' if px_pre_enabled else 'off'}`, then re-run reconcile."
                )
            if mf_result.file_states:
                existing_states = bundle.setdefault("file_states", {})
                for rel_path, state in mf_result.file_states.items():
                    existing_states[rel_path] = state
            if mf_result.restart_session_needed:
                mf_sr_section.changes.append(
                    "⟳ Files read by LLM sessions were modified. "
                    "Restart Claude Code / Gemini CLI for the changes to take effect."
                )
    except Exception as exc:  # noqa: BLE001
        mf_sr_section.ok = False
        mf_sr_section.detail = f"managed_files raised: {exc}"
    report.sections.append(mf_sr_section)
    _audit_append(target, {
        "ts": datetime.now(UTC).isoformat(),
        "actor": _actor(),
        "action": "apply-config:managed_files",
        "ok": mf_sr_section.ok,
        "detail": mf_sr_section.detail,
        "bundle": bundle_path.as_posix(),
    })

    # Section 7: persist the applied bundle as the new source of truth + UI
    # sidecar. Gated on the managed-files transaction: if managed_files failed
    # (and rolled its batch back), applied-config.json MUST NOT advance, so it
    # keeps matching the on-disk state.
    if mf_sr_section.ok:
        ab_sr = _write_applied_bundle(target, bundle)
    else:
        ab_sr = SectionResult(
            name="applied-bundle",
            section_id="applied-bundle",
            ok=False,
            detail="skipped: managed_files transaction failed — applied-config not advanced",
        )
    report.sections.append(ab_sr)

    # Section 8: regenerate files-state.js sidecar so the Files tab in the
    # config UI reflects the post-apply marker/SHA state. Best-effort —
    # failure here does NOT mark the overall apply as failed.
    fs_sr = SectionResult(name="files-state-sidecar", ok=True)
    try:
        from scripts import build_files_state as _bfs
        rc = _bfs.main(["--target", str(target), "--quiet"])
        if rc == 0:
            fs_sr.detail = "regenerated files-state.js"
        else:
            fs_sr.detail = f"build_files_state exited rc={rc}"
    except Exception as exc:  # noqa: BLE001
        fs_sr.detail = f"skipped: build_files_state raised ({exc})"
    report.sections.append(fs_sr)

    # Section 9: regenerate the telemetry-dashboard sidecar (best-effort).
    # Failure here must never break apply_config — log only.
    ds_sr = _rebuild_dashboard_sidecar(target)
    report.sections.append(ds_sr)

    return report


def _rebuild_dashboard_sidecar(target: Path) -> SectionResult:
    """Post-hook: invoke the telemetry-dashboard aggregator.

    Wrapped in try/except so any failure is captured as a non-fatal
    SectionResult — apply_config SHALL exit zero even when the aggregator
    fails (per openspec/changes/telemetry-dashboard/specs/
    telemetry-dashboard-aggregator/spec.md ``apply_config post-hook
    integration`` requirement).
    """
    sr = SectionResult(name="dashboard-sidecar", ok=True)
    try:
        # Imported lazily so apply_config keeps working on consumers that
        # have not yet bumped past the playbook version that ships this hook.
        from scripts.telemetry import build_dashboard_data
    except Exception as exc:  # noqa: BLE001 — best-effort.
        sr.ok = True  # not a failure of apply_config itself
        sr.detail = f"skipped: build_dashboard_data import failed ({exc})"
        return sr

    try:
        rc = build_dashboard_data.main([
            "--consumer-root", str(target),
            "--quiet",
        ])
    except SystemExit as exit_signal:
        rc = int(getattr(exit_signal, "code", 0) or 0)
    except Exception as exc:  # noqa: BLE001 — best-effort.
        sr.ok = True
        sr.detail = f"skipped: aggregator raised ({exc})"
        return sr

    if rc == 0:
        sr.detail = "regenerated dashboard-data.js"
    else:
        sr.detail = f"aggregator exited rc={rc} (sidecar may be stale)"
    return sr


