def apply_global_flags(
    target: Path,
    bundle: dict[str, Any],
    rules_env_entries: dict[str, str],
    global_flags_inventory: dict[str, Any] | None,
) -> SectionResult:
    sr = SectionResult(name="global_flags", ok=True)

    flag_intents = bundle.get("global_flags") or {}
    # Merge: rules-derived env entries come first (advanced sub-toggles), then
    # global_flags overlay on top (global wins on collision — unlikely but
    # explicit).
    env_entries: dict[str, str] = dict(rules_env_entries)

    if global_flags_inventory is not None:
        inv_by_key = {f["key"]: f for f in global_flags_inventory.get("flags", [])}
        for key, value in flag_intents.items():
            spec = inv_by_key.get(key)
            if spec is None:
                sr.changes.append(f"⚠ unknown global flag {key!r}; skipped")
                continue
            env_var = spec.get("env_var")
            if not env_var:
                continue
            v_on = spec.get("value_on", "1")
            v_off = spec.get("value_off", "")
            env_entries[env_var] = v_on if value else v_off

    if not env_entries and not flag_intents:
        sr.detail = "no global_flags or rules-derived env entries — no-op"
        return sr

    try:
        changes = _write_env_block(target, env_entries)
    except OSError as e:
        sr.ok = False
        sr.detail = f"failed to write feature-flags.env: {e}"
        return sr
    sr.changes.extend(changes)
    return sr


def _write_env_block(target: Path, env_entries: dict[str, str]) -> list[str]:
    """Write/update the marker block in <target>/.ai-playbook/feature-flags.env.

    Idempotent: if the file already contains the marker block, the block is
    replaced in place. If not, the block is appended (creating the file if
    needed). Lines outside the markers are preserved.

    Empty env_entries clears the block (writes the markers with no content
    inside, so future appends are still recognised).
    """
    p = target / STATE_DIR_NAME / FEATURE_FLAGS_FILENAME
    p.parent.mkdir(parents=True, exist_ok=True)

    text = p.read_text(encoding="utf-8") if p.is_file() else ""

    lines = text.split("\n")
    begin_idx = end_idx = None
    for i, line in enumerate(lines):
        if line == ENV_MARKER_BEGIN and begin_idx is None:
            begin_idx = i
        elif line == ENV_MARKER_END and begin_idx is not None and end_idx is None:
            end_idx = i

    new_block = [ENV_MARKER_BEGIN]
    for k in sorted(env_entries):
        v = env_entries[k]
        new_block.append(f"{k}={v}")
    new_block.append(ENV_MARKER_END)

    changes: list[str] = []
    if begin_idx is not None and end_idx is not None:
        # Replace existing block.
        new_lines = lines[:begin_idx] + new_block + lines[end_idx + 1:]
        changes.append(f"replaced env block ({end_idx - begin_idx - 1} → {len(env_entries)} entries)")
    else:
        # Append new block. Ensure single blank line separator if text exists.
        existing = [ln for ln in lines if ln.strip() != ""]
        new_lines = list(existing)
        if new_lines:
            new_lines.append("")
        new_lines.extend(new_block)
        new_lines.append("")
        changes.append(f"appended new env block ({len(env_entries)} entries) to {p}")

    body = "\n".join(new_lines).rstrip("\n") + "\n"
    p.write_text(body, encoding="utf-8")
    return changes


