"""Apply an ``ai-playbook-config/v1`` bundle JSON to a consumer project.

Bundle exported by ``config-ui/index.html`` (HTML UI) lands here. The
script projects each section to its on-disk representation:

    rules{}            → <target>/.ai-playbook/rules-toggle.json (direct write)
    features.caveman   → subprocess: python -m scripts.caveman on/off ...
    features.graphify  → subprocess: python -m scripts.graphify on/off ...
    features.ponytail  → subprocess: python -m scripts.ponytail on/off ...
    global_flags{}     → <target>/.ai-playbook/feature-flags.env (marker block)

Per-rule ``advanced{}`` sub-toggles (e.g. ``apply-skill-enforcement.advanced.bash_inspection``)
also project to the env file via the rules-inventory mapping. The L1 hook keeps
reading the env var as before; the bundle is just the declarative source.

Per the schema literal in ``schema-caveman-toggle-v1.json``:

> UI consumers MUST go through the CLI (python -m scripts.caveman) rather
> than touching the file directly.

So we subprocess. The caveman CLI handles backups, materialisation of the
AGENTS.md auto-managed block, and MCP wrapping — none of which we want to
re-implement.

Policy on errors: **best-effort per section**. A failure in one section is
reported in the audit log + the result, but the other sections still run.
Exit code is 0 if all sections succeeded, 1 if any failed.

CLI
---
    python -m scripts.apply_config <bundle.json> [--target PATH] [--dry-run] [--json]

Exit codes
----------
    0   all sections applied successfully (no-op sections count as success)
    1   one or more sections failed; see report
    2   environment/setup error (schema missing, jsonschema absent, ...)
"""
