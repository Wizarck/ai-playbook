@dataclass
class _ParsedEvents:
    events: list[dict] = field(default_factory=list)
    events_skipped: int = 0


def _iter_jsonl(path: Path) -> _ParsedEvents:
    out = _ParsedEvents()
    if not path.is_file():
        return out
    try:
        with path.open("r", encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if not line:
                    continue
                try:
                    obj = json.loads(line)
                except json.JSONDecodeError:
                    out.events_skipped += 1
                    continue
                if not isinstance(obj, dict):
                    out.events_skipped += 1
                    continue
                if obj.get("schema") != "rule-event/v2":
                    out.events_skipped += 1
                    continue
                out.events.append(obj)
    except OSError:
        return out
    return out


def _within_window(event: dict, start: _dt.datetime, end: _dt.datetime) -> bool:
    ts = event.get("timestamp")
    if not isinstance(ts, str):
        return False
    try:
        dt = _dt.datetime.fromisoformat(ts.replace("Z", "+00:00"))
    except ValueError:
        return False
    return start <= dt <= end


