def _is_hero_incident(event: dict) -> bool:
    """``verdict='block'`` AND no break-glass override; warnings excluded."""
    if event.get("verdict") != "block":
        return False
    return not event.get("override_reason")


def _is_llm01(event: dict) -> bool:
    """Prompt-injection signal: ``escape_hatch`` set OR ``bash_pattern_kind`` set.

    Per design.md decision D8 (post-correction): the rule-event/v2 schema does
    not carry a ``cmd_injection`` value in ``block_class``; the closed
    ``bash_pattern_kind`` enum captures every Bash-injection pattern the L1
    hook blocks, so any non-empty value counts as LLM01 evidence.
    """
    if event.get("escape_hatch"):
        return True
    return bool(event.get("bash_pattern_kind"))


def _compute_hero(events: Iterable[dict]) -> dict[str, int]:
    incidents = 0
    injection = 0
    for ev in events:
        if _is_hero_incident(ev):
            incidents += 1
            if _is_llm01(ev):
                injection += 1
    return {
        "incidents_prevented_7d": incidents,
        "prompt_injection_blocks": injection,
    }


def _health_emoji(obey_rate: float) -> str:
    if obey_rate >= HEALTH_GREEN_FLOOR:
        return "green"
    if obey_rate >= HEALTH_YELLOW_FLOOR:
        return "yellow"
    return "red"


def _compute_obey_rate(events: list[dict]) -> float:
    if not events:
        return 0.0
    allowed = sum(1 for ev in events if ev.get("verdict") in {"allow", "warn"})
    return allowed / len(events)


def _compute_trend(
    events: list[dict],
    window_start: _dt.datetime,
    window_end: _dt.datetime,
) -> list[dict[str, Any]]:
    """Per-day buckets across the window."""
    by_day: dict[str, list[dict]] = defaultdict(list)
    for ev in events:
        ts = ev.get("timestamp")
        if not isinstance(ts, str):
            continue
        try:
            dt = _dt.datetime.fromisoformat(ts.replace("Z", "+00:00"))
        except ValueError:
            continue
        iso_day = dt.date().isoformat()
        by_day[iso_day].append(ev)

    points: list[dict[str, Any]] = []
    cursor = window_start.date()
    last_day = window_end.date()
    while cursor <= last_day:
        iso_day = cursor.isoformat()
        bucket = by_day.get(iso_day, [])
        rate = _compute_obey_rate(bucket) if bucket else 0.0
        points.append(
            {
                "iso_day": iso_day,
                "obey_rate": round(rate, 4),
                "events": len(bucket),
            }
        )
        cursor += _dt.timedelta(days=1)
    return points


def _compute_matrix(
    events: list[dict],
    prior_events: list[dict],
) -> list[dict[str, Any]]:
    """Rule × LLM agreement, with drift_flag in two senses."""
    # Current window: per-(slug, llm) obey-rate.
    cur_counts: dict[tuple[str, str], list[int]] = defaultdict(lambda: [0, 0])  # [n_allow_or_warn, n_total]
    for ev in events:
        slug = ev.get("slug")
        llm = ev.get("llm")
        if not slug or not llm:
            continue
        cur_counts[(slug, llm)][1] += 1
        if ev.get("verdict") in {"allow", "warn"}:
            cur_counts[(slug, llm)][0] += 1

    prior_counts: dict[tuple[str, str], list[int]] = defaultdict(lambda: [0, 0])
    for ev in prior_events:
        slug = ev.get("slug")
        llm = ev.get("llm")
        if not slug or not llm:
            continue
        prior_counts[(slug, llm)][1] += 1
        if ev.get("verdict") in {"allow", "warn"}:
            prior_counts[(slug, llm)][0] += 1

    # Build per-slug rows.
    slugs = sorted({k[0] for k in cur_counts})
    rows: list[dict[str, Any]] = []
    for slug in slugs:
        by_llm: dict[str, float] = {}
        slug_total = 0
        for (s, llm), (good, total) in cur_counts.items():
            if s != slug or total == 0:
                continue
            by_llm[llm] = round(good / total, 4)
            slug_total += total

        if not by_llm:
            continue

        # Drift sense 1: cross-LLM disagreement.
        cross_drift = (
            (max(by_llm.values()) - min(by_llm.values())) > CROSS_LLM_DRIFT_THRESHOLD
            if len(by_llm) >= 2
            else False
        )

        # Drift sense 2: per-LLM time-over-time, against prior window.
        time_drift = False
        for llm, rate_now in by_llm.items():
            good_p, total_p = prior_counts.get((slug, llm), [0, 0])
            if total_p == 0:
                continue
            rate_prior = good_p / total_p
            if abs(rate_now - rate_prior) > TIME_OVER_TIME_DRIFT_THRESHOLD:
                time_drift = True
                break

        # Suppress drift signalling on under-sampled rows.
        if slug_total < MATRIX_DRIFT_MIN_EVENTS:
            cross_drift = False
            time_drift = False

        if cross_drift and time_drift:
            flag = "both"
        elif cross_drift:
            flag = "cross_llm"
        elif time_drift:
            flag = "time_over_time"
        else:
            flag = "none"

        rows.append(
            {
                "rule_slug": slug,
                "by_llm": by_llm,
                "drift_flag": flag,
            }
        )
    return rows


def _compute_honesty(events: list[dict]) -> list[dict[str, Any]]:
    """Self_check ↔ verdict agreement per LLM.

    Denominator (design.md Q2 closed here): events where a verdict was produced
    (allow / block / warn). Since verdict is a required field in rule-event/v2,
    that is every well-formed event.

    Agreement: ``self_check == (verdict == "allow")``. The LLM correctly reports
    rule-following when it claims it followed and the hook saw allow; correctly
    reports breaking when it claims it broke and the hook saw block or warn.
    """
    per_llm: dict[str, list[int]] = defaultdict(lambda: [0, 0])  # [agreements, total]
    for ev in events:
        llm = ev.get("llm")
        if not llm:
            continue
        verdict = ev.get("verdict")
        if verdict not in {"allow", "block", "warn"}:
            continue
        self_check = bool(ev.get("self_check"))
        claimed_followed = self_check
        actually_followed = verdict == "allow"
        per_llm[llm][1] += 1
        if claimed_followed == actually_followed:
            per_llm[llm][0] += 1

    rows: list[dict[str, Any]] = []
    for llm in sorted(per_llm):
        agree, total = per_llm[llm]
        if total < HONESTY_MIN_EVENTS:
            # Suppress under-sampled rows; do not fabricate signal.
            continue
        rows.append(
            {
                "llm": llm,
                "self_check_verdict_agreement_rate": round(agree / total, 4),
                "n_events": total,
            }
        )
    return rows


def _compute_friction(events: list[dict]) -> list[dict[str, Any]]:
    by_slug_override: dict[str, list[str]] = defaultdict(list)
    by_slug_count: Counter[str] = Counter()
    for ev in events:
        if ev.get("verdict") != "block":
            continue
        reason = ev.get("override_reason")
        if not reason:
            continue
        slug = ev.get("slug")
        if not slug:
            continue
        by_slug_count[slug] += 1
        by_slug_override[slug].append(reason)

    rows: list[dict[str, Any]] = []
    for slug, count in by_slug_count.most_common(FRICTION_TOP_RULES):
        top_reasons = [r for r, _ in Counter(by_slug_override[slug]).most_common(FRICTION_TOP_REASONS)]
        rows.append(
            {
                "rule_slug": slug,
                "break_glass_count": count,
                "override_reasons_top": top_reasons,
            }
        )
    return rows


