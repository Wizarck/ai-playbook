# Output sidecar schema. Renderer rejects mismatches.
SCHEMA_VERSION = "dashboard-data/v1"

# Below this event count, the renderer shows the pedagogical empty state.
DEFAULT_EMPTY_STATE_THRESHOLD = 100

# Drift detection thresholds (design.md §Open Questions Q1, closed here).
# Cross-LLM disagreement: max minus min `by_llm` value exceeds this → drift.
CROSS_LLM_DRIFT_THRESHOLD = 0.10
# Per-LLM time-over-time delta: |current - prior| exceeds this → drift.
TIME_OVER_TIME_DRIFT_THRESHOLD = 0.05

# Per-rule sample-size floors for honesty meter and matrix drift detection.
HONESTY_MIN_EVENTS = 50
MATRIX_DRIFT_MIN_EVENTS = 30

# Friction panel: top-N rules and top-N override reasons per rule.
FRICTION_TOP_RULES = 5
FRICTION_TOP_REASONS = 3

# Cost methodology link (used by the renderer's cost panel tooltip).
# Relative to config-ui/index.html, which sits one level below the playbook
# docs tree (<consumer>/.ai-playbook/config-ui/ → ../docs/...). Must match the
# sibling TELEMETRY_DESIGN_DOC convention in config-ui/dashboard.js.
COST_METHODOLOGY_URL = "../docs/concepts/caveman-mode.md#cost-methodology"

# Health-emoji thresholds (driven by obey_rate_7d).
HEALTH_GREEN_FLOOR = 0.95
HEALTH_YELLOW_FLOOR = 0.85

# Pedagogical empty-state copy. Tech-writing polish lives in v2 candidates.
EMPTY_STATE_COPY = (
    "No telemetry yet. The dashboard becomes meaningful after ~100 rule-event/v2 "
    "events accumulate in this repo. Use the playbook as you normally would; "
    "the data lands on its own. See docs/concepts/telemetry-design.md for what "
    "each event records."
)

# Privacy guard: target_rel must look like a glob (contain '*' or end with a
# scrubbed marker). Anything that looks like a raw path is replaced.
_GLOB_LIKE = re.compile(r"[*?\[\]]")

# Single-line JS sidecar wrapper.
_JS_HEADER = "// generated by scripts/telemetry/build_dashboard_data.py — do not edit by hand\n"
_JS_PREFIX = "window.DASHBOARD_DATA = "
_JS_SUFFIX = ";\n"


# ---------------------------------------------------------------------------
# IO helpers.
# ---------------------------------------------------------------------------


def _utcnow() -> _dt.datetime:
    return _dt.datetime.now(_dt.UTC).replace(microsecond=0)


def _iso(dt: _dt.datetime) -> str:
    return dt.isoformat().replace("+00:00", "Z")


def _sha256_of_file(path: Path) -> str | None:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def _atomic_write(path: Path, payload: str) -> None:
    """Write ``payload`` to ``path`` atomically (temp + os.replace)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(payload, encoding="utf-8", newline="\n")
    os.replace(tmp, path)


def _scrub_target_rel(value: Any) -> str | None:
    """Return ``value`` if it looks like a glob, else replace with marker.

    Privacy invariant: individual file paths must never reach the sidecar.
    The playbook scrubs at write time; this is the second-line check at
    display time.
    """
    if not isinstance(value, str) or not value:
        return None
    if _GLOB_LIKE.search(value):
        return value
    # Common scrubbed sentinels (e.g. "*.env", "**/secrets/*") would have matched
    # above. Anything that looks like a literal path is suspicious.
    return "<scrub-violation>"


