def _read_caveman_json(consumer_root: Path) -> dict | None:
    p = consumer_root / ".ai-playbook" / "caveman.json"
    if not p.is_file():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def _resolve_caveman_state(consumer_root: Path) -> str:
    state = _read_caveman_json(consumer_root)
    if state is None:
        return "missing"
    if state.get("enabled"):
        return "on"
    return "off"


def _invoke_caveman_stats(consumer_root: Path, quiet: bool) -> dict | None:
    """Best-effort: invoke caveman stats and return the dict, else None."""
    try:
        from scripts.caveman import stats as caveman_stats  # type: ignore
    except Exception:
        caveman_stats = None  # type: ignore

    if caveman_stats is None:
        # Fall back to subprocess (handles cases where caveman is dynamically reloaded).
        try:
            result = subprocess.run(
                [sys.executable, "-m", "scripts.caveman.stats", "--json"],
                capture_output=True,
                text=True,
                timeout=20,
                cwd=consumer_root,
            )
            if result.returncode != 0:
                return None
            return json.loads(result.stdout)
        except (OSError, subprocess.TimeoutExpired, json.JSONDecodeError):
            return None

    try:
        session_stats = caveman_stats.collect_stats(consumer_root)
        saved = caveman_stats.extrapolated_savings(session_stats.output_tokens)
        cost_saved = (saved / 1_000_000.0) * caveman_stats.COST_PER_M_OUTPUT_USD
    except Exception:  # noqa: BLE001 — caveman is best-effort.
        return None

    state = _read_caveman_json(consumer_root) or {}
    return {
        "mode": state.get("mode", "ultra"),
        "components": state.get("components") or {},
        "activation_rate": 0.0 if session_stats.sessions == 0 else 1.0,
        "tokens_in_total": session_stats.input_tokens,
        "tokens_out_total": session_stats.output_tokens,
        "tokens_in_delta": 0,
        "tokens_out_delta": -saved,
        "cost_saved_usd": round(cost_saved, 2),
    }


def _compute_caveman_panel(consumer_root: Path, quiet: bool) -> tuple[str, dict]:
    state = _resolve_caveman_state(consumer_root)
    if state != "on":
        return state, {"state": state}

    raw = _invoke_caveman_stats(consumer_root, quiet=quiet)
    if not raw:
        # Treat invocation failure as missing — better than silently fabricating data.
        return "missing", {"state": "missing"}

    panel = {
        "activation_rate": float(raw.get("activation_rate", 0.0)),
        "mode": raw.get("mode", "ultra"),
        "components": {k: bool(v) for k, v in (raw.get("components") or {}).items()},
        "tokens_in_delta": int(raw.get("tokens_in_delta", 0)),
        "tokens_out_delta": int(raw.get("tokens_out_delta", 0)),
        "cost_saved_usd": float(raw.get("cost_saved_usd", 0.0)),
    }
    return state, panel


