"""Offline aggregator for the telemetry dashboard.

Reads:
- ``<consumer>/.ai-playbook-state/rule-events.jsonl`` (rule-event/v2 schema).
- The JSON output of ``scripts/caveman/stats.py`` (via direct import).
- ``configs/pricing.yaml`` (sha256-pinned at run time).

Writes a single sidecar at ``<consumer>/.ai-playbook/dashboard-data.js`` of the
form ``window.DASHBOARD_DATA = { ... };``. The browser loads it via
``<script src>`` from ``config-ui/index.html`` (``fetch()`` is blocked on
``file://``). Writes are atomic (temp + rename); torn JSONL lines are skipped
without crashing.

This module is invoked:
- Directly by developers: ``python -m scripts.telemetry.build_dashboard_data``.
- Automatically by ``scripts/apply_config.py`` as a post-hook on every
  successful config-bundle apply.

See:
- ``docs/concepts/telemetry-dashboard.md`` for the panel design.
- ``schemas/schema-dashboard-data-v1.json`` for the output contract.
- ``openspec/changes/telemetry-dashboard/`` for the change-tracked proposal.
"""

