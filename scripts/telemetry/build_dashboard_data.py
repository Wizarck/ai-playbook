def _parse_window(value: str) -> int:
    value = value.strip().lower()
    if value in {"7", "7d", "7days"}:
        return 7
    if value in {"30", "30d", "30days"}:
        return 30
    raise argparse.ArgumentTypeError("window must be one of: 7d, 30d")


def _build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m scripts.telemetry.build_dashboard_data",
        description="Build the dashboard-data/v1 sidecar from local telemetry.",
    )
    parser.add_argument(
        "--window",
        type=_parse_window,
        default=7,
        help="Aggregation window in days. Allowed values: 7d, 30d. Default: 7d.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help=(
            "Output sidecar path. Default: "
            "<consumer-root>/.ai-playbook/dashboard-data.js."
        ),
    )
    parser.add_argument(
        "--consumer-root",
        type=Path,
        default=None,
        help="Consumer repo root. Default: current working directory.",
    )
    parser.add_argument(
        "--state-dir",
        type=Path,
        default=None,
        help=(
            "Override the telemetry state directory. Default: "
            "$AI_PLAYBOOK_STATE_DIR or <consumer-root>/.ai-playbook-state/."
        ),
    )
    parser.add_argument(
        "--pricing-path",
        type=Path,
        default=None,
        help="Path to pricing.yaml. Default: <playbook>/configs/pricing.yaml.",
    )
    parser.add_argument(
        "--schema-path",
        type=Path,
        default=None,
        help=(
            "Path to the dashboard-data/v1 JSON schema. Default: "
            "<playbook>/schemas/schema-dashboard-data-v1.json."
        ),
    )
    parser.add_argument(
        "--empty-state-threshold",
        type=int,
        default=DEFAULT_EMPTY_STATE_THRESHOLD,
        help="Threshold below which the renderer shows the empty state.",
    )
    parser.add_argument(
        "--quiet",
        action="store_true",
        help="Suppress informational stdout messages.",
    )
    parser.add_argument(
        "--no-validate",
        action="store_true",
        help="Skip JSON schema validation of the output payload (not recommended).",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _build_arg_parser().parse_args(argv)

    consumer_root = (args.consumer_root or _default_consumer_root()).resolve()
    output_path = (args.output or _default_output(consumer_root)).resolve()

    here = Path(__file__).resolve()
    playbook_root = here.parent.parent.parent  # scripts/telemetry/build_dashboard_data.py → playbook root

    pricing_path = (args.pricing_path or (playbook_root / "configs" / "pricing.yaml")).resolve()
    schema_path = (args.schema_path or (playbook_root / "schemas" / "schema-dashboard-data-v1.json")).resolve()

    payload = build_payload(
        consumer_root=consumer_root,
        state_dir=args.state_dir,
        window_days=args.window,
        pricing_path=pricing_path,
        empty_state_threshold=args.empty_state_threshold,
        quiet=args.quiet,
    )

    if not args.no_validate:
        errors = _validate_against_schema(payload, schema_path)
        if errors:
            print("dashboard-data payload failed schema validation:", file=sys.stderr)
            for err in errors[:20]:
                print(f"  - {err}", file=sys.stderr)
            return 2

    _atomic_write(output_path, _render_sidecar_js(payload))

    if not args.quiet:
        ev = payload["window"]
        print(
            f"build_dashboard_data: wrote {output_path} "
            f"(window={args.window}d, events_seen={ev['events_seen']}, "
            f"events_skipped={ev['events_skipped']}, "
            f"caveman_state={payload['caveman_state']})"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
