def _scrub_event_inplace(event: dict) -> dict:
    """Apply the second-line privacy guards expected by the spec."""
    if "target_rel" in event:
        scrubbed = _scrub_target_rel(event.get("target_rel"))
        if scrubbed is None:
            event.pop("target_rel", None)
        else:
            event["target_rel"] = scrubbed
    # Raw Bash commands must never appear; rule-event/v2 doesn't carry them,
    # but defensively drop any unexpected ``bash_command`` field.
    event.pop("bash_command", None)
    return event


def build_payload(
    consumer_root: Path,
    state_dir: Path | None,
    window_days: int,
    pricing_path: Path,
    empty_state_threshold: int,
    *,
    quiet: bool = False,
) -> dict:
    state_dir_resolved = _resolve_state_dir(state_dir, consumer_root)
    events_path = state_dir_resolved / "rule-events.jsonl"
    parsed = _iter_jsonl(events_path)

    now = _utcnow()
    window_start = now - _dt.timedelta(days=window_days)
    prior_start = window_start - _dt.timedelta(days=window_days)

    in_window: list[dict] = []
    in_prior: list[dict] = []
    for raw in parsed.events:
        ev = _scrub_event_inplace(dict(raw))
        if _within_window(ev, window_start, now):
            in_window.append(ev)
        elif _within_window(ev, prior_start, window_start):
            in_prior.append(ev)

    events_seen = len(in_window)
    events_skipped = parsed.events_skipped

    pricing_sha = _sha256_of_file(pricing_path) or ("0" * 64)

    payload: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "generated_at": _iso(now),
        "pricing_version": pricing_sha,
        "window": {
            "days": window_days,
            "from_iso": _iso(window_start),
            "to_iso": _iso(now),
            "events_seen": events_seen,
            "events_skipped": events_skipped,
        },
        "empty_state_threshold": empty_state_threshold,
    }

    caveman_state, caveman_panel = _compute_caveman_panel(consumer_root, quiet=quiet)
    payload["caveman_state"] = caveman_state

    ponytail_state, ponytail_panel = _compute_ponytail_panel(consumer_root, _iso(window_start))
    payload["ponytail_state"] = ponytail_state

    if events_seen < empty_state_threshold:
        # Empty-state branch: emit zero-filled panel scaffolds so the renderer
        # has a consistent shape; the renderer suppresses contents itself.
        payload["panels"] = {
            "hero": {"incidents_prevented_7d": 0, "prompt_injection_blocks": 0},
            "secondary": {
                "obey_rate_7d": 0.0,
                "cost_saved_usd": {"value": 0.0, "methodology": COST_METHODOLOGY_URL},
                "health_emoji": "red",
            },
            "trend": {"points": []},
            "matrix": {"rows": []},
            "honesty": {"rows": []},
            "friction": {"rows": []},
            "caveman": caveman_panel,
            "ponytail": ponytail_panel,
        }
        return payload

    hero = _compute_hero(in_window)
    obey_rate = round(_compute_obey_rate(in_window), 4)
    cost_value = float(caveman_panel.get("cost_saved_usd", 0.0)) if caveman_state == "on" else 0.0

    payload["panels"] = {
        "hero": hero,
        "secondary": {
            "obey_rate_7d": obey_rate,
            "cost_saved_usd": {
                "value": round(cost_value, 2),
                "methodology": COST_METHODOLOGY_URL,
            },
            "health_emoji": _health_emoji(obey_rate),
        },
        "trend": {"points": _compute_trend(in_window, window_start, now)},
        "matrix": {"rows": _compute_matrix(in_window, in_prior)},
        "honesty": {"rows": _compute_honesty(in_window)},
        "friction": {"rows": _compute_friction(in_window)},
        "caveman": caveman_panel,
        "ponytail": ponytail_panel,
    }
    return payload


def _validate_against_schema(payload: dict, schema_path: Path) -> list[str]:
    try:
        import jsonschema  # type: ignore
    except ImportError:
        return []  # Validation is best-effort if jsonschema is not installed.

    try:
        schema = json.loads(schema_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return [f"schema load failed: {exc}"]

    v = jsonschema.Draft202012Validator(schema)
    return [
        f"{'/'.join(str(p) for p in err.absolute_path) or '<root>'}: {err.message}"
        for err in v.iter_errors(payload)
    ]


def _render_sidecar_js(payload: dict) -> str:
    body = json.dumps(payload, indent=2, sort_keys=True)
    return _JS_HEADER + _JS_PREFIX + body + _JS_SUFFIX


